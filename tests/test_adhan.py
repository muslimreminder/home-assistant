"""The Python port gives the times of adhan-js, the library of the app."""

from __future__ import annotations

from datetime import date
import json
from pathlib import Path

import pytest

from custom_components.muslim_reminder import adhan
from custom_components.muslim_reminder.calculation import build_parameters, effective_method, times_for_day
from custom_components.muslim_reminder.const import METHODS

CASES = json.loads((Path(__file__).parent / "fixtures" / "adhan_reference.json").read_text())


def _params(case: dict) -> adhan.CalculationParameters:
    if "rule" in case:
        params = adhan.calculation_method("MuslimWorldLeague")
        params.high_latitude_rule = case["rule"]
        params.polar_circle_resolution = case["polar"]
        return params
    adjustments = (
        {"fajr": -2, "sunrise": 1, "dhuhr": 3, "asr": -4, "maghrib": 5, "isha": -6} if case["adjusted"] else {}
    )
    return build_parameters({"method": case["method"], "madhab": case["madhab"], "adjustments": adjustments}, None)


def test_every_reference_time() -> None:
    """6,912 days × places × methods × madhabs, generated by scripts/adhan_reference.mjs."""
    mismatches = []
    for case in CASES:
        day = date.fromisoformat(case["day"])
        expected = case["times"]
        try:
            got = {
                name: moment.strftime("%Y-%m-%dT%H:%M:%SZ")
                for name, moment in adhan.prayer_times(day, case["latitude"], case["longitude"], _params(case)).items()
            }
        except ValueError:
            # adhan-js returns Invalid Date where the sun neither rises nor sets.
            assert any(value is None for value in expected.values()), case
            continue
        if got != expected:
            mismatches.append((case["place"], case["day"], case["method"], case["madhab"], got, expected))
    assert not mismatches, mismatches[:5]
    assert len(CASES) == 6912


def test_every_method_of_the_app_is_covered() -> None:
    assert {case["method"] for case in CASES} == set(METHODS) - {"CUSTOM"}


@pytest.mark.parametrize(
    ("method", "country", "expected"),
    [
        ("auto", "FR", "FRANCE_18"),
        ("auto", "ma", "MOROCCO"),
        ("auto", "DE", "MUSLIM_WORLD_LEAGUE"),
        ("auto", None, "MUSLIM_WORLD_LEAGUE"),
        ("umm_alqura", "FR", "UMM_ALQURA"),
        ("unknown", "SA", "UMM_ALQURA"),
    ],
)
def test_automatic_method(method: str, country: str | None, expected: str) -> None:
    assert effective_method(method, country) == expected


def test_custom_angles_replace_those_of_the_method() -> None:
    params = build_parameters({"method": "france_18", "fajr_angle": 12, "isha_angle": 12.5, "maghrib_angle": 4}, "FR")
    assert (params.fajr_angle, params.isha_angle, params.maghrib_angle) == (12, 12.5, 4)
    assert params.high_latitude_rule == adhan.TWILIGHT_ANGLE


def test_polar_day_falls_back_to_the_nearest_latitude() -> None:
    """Tromsø, midsummer: adhan-js gives no sunset, the house still gets times."""
    params = build_parameters({"method": "muslim_world_league"}, None)
    with pytest.raises(ValueError):
        adhan.prayer_times(date(2026, 6, 21), 69.6492, 18.9553, params)
    times = times_for_day(date(2026, 6, 21), 69.6492, 18.9553, params)
    assert times["fajr"] < times["sunrise"] < times["dhuhr"] < times["asr"] < times["maghrib"] <= times["isha"]
